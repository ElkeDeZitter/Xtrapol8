#!/bin/bash
# Build a lightweight macOS launcher, Xtrapol8.app, for the Xtrapol8 Qt GUI.
#
# The app does not bundle Python, cctbx, Phenix or CCP4. At launch it finds
# the installed CCP4 and Phenix, sources their environment scripts (apps
# started from Finder/Dock do not read ~/.zprofile), and runs the Xtrapol8
# GUI with a Python that has xtrapol8 installed (CCP4's Python by default).
#
# Usage:  macos/make_app.sh [DEST_DIR]      (default: ./dist)
# Then drag DEST_DIR/Xtrapol8.app into /Applications or ~/Applications.
#
# Optional settings for the launcher go in ~/.xtrapol8_app.conf, e.g.
#   X8_CCP4=/Applications/ccp4-9
#   X8_PHENIX=/Applications/phenix-1.21.2-5419
#   X8_PYTHON=/path/to/python3

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${1:-$REPO/dist}"
APP="$DEST/Xtrapol8.app"
ICON_SRC="$REPO/xtrapol8/gui/assets/Xtrapol8_logo_dock.png"
vpart() { sed -n "s/^$1 *= *\([0-9][0-9]*\).*/\1/p" "$REPO/xtrapol8/__init__.py" | head -1; }
VERSION="$(vpart MAJOR).$(vpart MINOR).$(vpart PATCH)"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || VERSION="0.0.0"

echo "Building $APP (version $VERSION)"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# --- Info.plist --------------------------------------------------------------
cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>               <string>Xtrapol8</string>
    <key>CFBundleDisplayName</key>        <string>Xtrapol8</string>
    <key>CFBundleIdentifier</key>         <string>org.xtrapol8.gui</string>
    <key>CFBundleVersion</key>            <string>$VERSION</string>
    <key>CFBundleShortVersionString</key> <string>$VERSION</string>
    <key>CFBundlePackageType</key>        <string>APPL</string>
    <key>CFBundleExecutable</key>         <string>Xtrapol8</string>
    <key>CFBundleIconFile</key>           <string>Xtrapol8</string>
    <key>LSMinimumSystemVersion</key>     <string>10.13</string>
    <key>NSHighResolutionCapable</key>    <true/>
</dict>
</plist>
EOF

# --- Icon --------------------------------------------------------------------
if [[ -f "$ICON_SRC" ]]; then
    TMP="$(mktemp -d)"
    ICONSET="$TMP/Xtrapol8.iconset"
    mkdir -p "$ICONSET"
    for s in 16 32 128 256 512; do
        sips -z $s $s "$ICON_SRC" --out "$ICONSET/icon_${s}x${s}.png" >/dev/null
        sips -z $((s*2)) $((s*2)) "$ICON_SRC" --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null
    done
    iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/Xtrapol8.icns"
    rm -rf "$TMP"
else
    echo "Warning: icon not found at $ICON_SRC; building without icon" >&2
fi

# --- Launcher ----------------------------------------------------------------
cat > "$APP/Contents/MacOS/Xtrapol8" <<'LAUNCHER'
#!/bin/bash
# Xtrapol8.app launcher (generated by macos/make_app.sh).

LOG_DIR="$HOME/Library/Logs/Xtrapol8"
LOG="$LOG_DIR/launcher.log"
mkdir -p "$LOG_DIR"
exec >>"$LOG" 2>&1
echo "=== $(date) ==="

fail() {
    echo "ERROR: $1"
    /usr/bin/osascript - "$1" "$LOG" <<'EOF' >/dev/null 2>&1
on run argv
    display dialog (item 1 of argv) & return & return & "Details: " & (item 2 of argv) ¬
        with title "Xtrapol8" buttons {"OK"} default button "OK" with icon stop
end run
EOF
    exit 1
}

# Newest directory matching the given globs (by version-aware sort).
newest() {
    local d
    for d in "$@"; do [[ -d "$d" ]] && echo "$d"; done | sort -V | tail -1
}

CONF="$HOME/.xtrapol8_app.conf"
[[ -f "$CONF" ]] && source "$CONF"

shopt -s nullglob

# --- CCP4 ---
CCP4_DIR="${X8_CCP4:-$(newest /Applications/ccp4-* "$HOME"/Applications/ccp4-*)}"
if [[ -n "$CCP4_DIR" && -f "$CCP4_DIR/bin/ccp4.setup-sh" ]]; then
    echo "CCP4:   $CCP4_DIR"
    source "$CCP4_DIR/bin/ccp4.setup-sh"
else
    echo "CCP4 not found (refmac5/coot will be unavailable)"
fi

# --- Phenix ---
PHENIX_DIR="${X8_PHENIX:-$(newest /Applications/phenix-* "$HOME"/Applications/phenix-*)}"
if [[ -n "$PHENIX_DIR" && -f "$PHENIX_DIR/phenix_env.sh" ]]; then
    echo "Phenix: $PHENIX_DIR"
    source "$PHENIX_DIR/phenix_env.sh"
else
    echo "Phenix not found (phenix.refine will be unavailable)"
fi

# --- Python with xtrapol8 ---
has_x8() { [[ -x "$1" ]] && "$1" -c "import xtrapol8.gui.main" >/dev/null 2>&1; }

PY=""
CANDIDATES=()
[[ -n "${X8_PYTHON:-}" ]] && CANDIDATES+=("$X8_PYTHON")
[[ -n "$CCP4_DIR" ]] && CANDIDATES+=("$CCP4_DIR"/Frameworks/Python.framework/Versions/Current/bin/python3 "$CCP4_DIR"/Frameworks/Python.framework/Versions/3*/bin/python3 "$CCP4_DIR"/bin/ccp4-python)
[[ -n "$PHENIX_DIR" ]] && CANDIDATES+=("$PHENIX_DIR"/bin/python3 "$PHENIX_DIR"/bin/python)
for c in "${CANDIDATES[@]}"; do
    if has_x8 "$c"; then PY="$c"; break; fi
done

if [[ -z "$PY" ]]; then
    fail "Could not find a Python with Xtrapol8 installed.

Install it into CCP4's Python, e.g.:
<ccp4>/Frameworks/Python.framework/Versions/3.9/bin/python3 -m pip install -e <Xtrapol8 folder>

or set X8_PYTHON in ~/.xtrapol8_app.conf."
fi

echo "Python: $PY"
cd "$HOME"
exec "$PY" -m xtrapol8.gui.main "$@"
LAUNCHER
chmod +x "$APP/Contents/MacOS/Xtrapol8"

# Ad-hoc signature so Gatekeeper treats the bundle consistently.
codesign --force --deep -s - "$APP" >/dev/null 2>&1 || true

echo "Done: $APP"
echo "Drag it to /Applications (or ~/Applications) to install."
